"""LangGraph checkpoint 隔离与节点重放测试。

MEMORY.md 把「LangGraph 节点从中断恢复时从头重放」列为已知结构性风险。
本文件是那条风险的**可执行证据**:证明风险真实存在，且缓解措施有效。
"""

